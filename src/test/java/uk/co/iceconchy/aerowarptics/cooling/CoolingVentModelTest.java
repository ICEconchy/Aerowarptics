package uk.co.iceconchy.aerowarptics.cooling;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The vent a player sees blows the way the block says it does, and takes its shaft where the block does.
 *
 * <p>The model is generated by {@code tools/cooling_vent_model.py}; which face the steam leaves by and which
 * the shaft comes in at are written by hand in {@link CoolingVentBlock}, and the client throws the steam
 * out along the block's facing. Nothing ties those together, and a mismatch is silent: louvres on one face
 * and steam out of another, or a shaft that connects to a blank side. Read from the files rather than the
 * block class, which cannot be loaded without a bootstrapped Minecraft.
 */
class CoolingVentModelTest {

    private static final Path ASSETS = Path.of("src/main/resources/assets/aerowarptics");
    private static final Path DATA = Path.of("src/main/resources/data");
    private static final Path SOURCES = Path.of("src/main/java/uk/co/iceconchy/aerowarptics");

    private static JsonObject read(Path path) {
        try (Reader reader = Files.newBufferedReader(path, StandardCharsets.UTF_8)) {
            return JsonParser.parseReader(reader).getAsJsonObject();
        } catch (IOException e) {
            throw new AssertionError("could not read " + path, e);
        }
    }

    private static String source(String path) {
        try {
            return Files.readString(SOURCES.resolve(path), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new AssertionError("could not read " + path, e);
        }
    }

    private static List<JsonObject> elements() {
        List<JsonObject> elements = new ArrayList<>();
        for (JsonElement element : read(ASSETS.resolve("models/block/cooling_vent.json")).getAsJsonArray("elements")) {
            elements.add(element.getAsJsonObject());
        }
        return elements;
    }

    private static double at(JsonObject element, String corner, int axis) {
        return element.getAsJsonArray(corner).get(axis).getAsDouble();
    }

    /**
     * The model's louvres are on its north face, and the blockstate turns that face to each facing the way
     * vanilla turns an observer, whose working face is north too. Any other table points the louvres one
     * way while the block throws its steam out of another.
     */
    @Test
    void everyFacingTurnsTheLouvresToTheFaceTheSteamLeavesBy() {
        JsonObject variants = read(ASSETS.resolve("blockstates/cooling_vent.json")).getAsJsonObject("variants");
        Map<String, int[]> observer = Map.of(
                "north", new int[]{0, 0}, "east", new int[]{0, 90}, "south", new int[]{0, 180},
                "west", new int[]{0, 270}, "up", new int[]{270, 0}, "down", new int[]{90, 0});
        assertEquals(observer.size(), variants.size(), "one variant for each facing and no others");
        for (Map.Entry<String, int[]> entry : observer.entrySet()) {
            JsonObject variant = variants.getAsJsonObject("facing=" + entry.getKey());
            assertTrue(variant != null, "no variant for facing=" + entry.getKey());
            assertEquals("aerowarptics:block/cooling_vent", variant.get("model").getAsString());
            assertEquals(entry.getValue()[0], variant.has("x") ? variant.get("x").getAsInt() : 0,
                    "x turn for " + entry.getKey());
            assertEquals(entry.getValue()[1], variant.has("y") ? variant.get("y").getAsInt() : 0,
                    "y turn for " + entry.getKey());
        }
    }

    @Test
    void theShaftSocketIsOnTheFaceOppositeTheLouvres() {
        int sockets = 0;
        int louvres = 0;
        for (JsonObject element : elements()) {
            for (Map.Entry<String, JsonElement> face : element.getAsJsonObject("faces").entrySet()) {
                if (face.getValue().getAsJsonObject().get("texture").getAsString().equals("#back")) {
                    sockets++;
                    assertEquals("south", face.getKey(), "the shaft socket is drawn on a face that is not the back");
                    assertEquals(16.0D, at(element, "to", 2), "the socket is not on the outside of the block");
                }
            }
            if (element.has("rotation")) {
                louvres++;
                assertTrue(at(element, "to", 2) < 8.0D, "a louvre sits in the back half of the vent");
            }
        }
        assertEquals(1, sockets, "one shaft socket");
        assertTrue(louvres >= 2, "a vent with fewer than two louvres is a hole with a bar across it");

        // The block's half of the same statement.
        String block = source("cooling/CoolingVentBlock.java");
        assertTrue(block.contains("return face == state.getValue(FACING).getOpposite();"),
                "the block no longer takes its shaft at the back, where the model draws the socket");
    }

    /**
     * A tilted louvre has to stay inside the opening it is in. One that reaches past the rim is drawn
     * through the casing, and one that reaches past the block's face is drawn in the block next door.
     */
    @Test
    void theLouvresStayInsideTheirOpening() {
        double rim = Double.NaN;
        double throat = Double.NaN;
        for (JsonObject element : elements()) {
            for (Map.Entry<String, JsonElement> face : element.getAsJsonObject("faces").entrySet()) {
                if (face.getValue().getAsJsonObject().get("texture").getAsString().equals("#throat")) {
                    throat = at(element, "from", 2);
                }
            }
            // The bottom wall: full width, on the floor, shorter than the block is tall.
            if (!element.has("rotation") && at(element, "from", 1) == 0.0D && at(element, "to", 1) < 8.0D) {
                rim = at(element, "to", 1);
            }
        }
        assertFalse(Double.isNaN(rim) || Double.isNaN(throat), "could not find the opening in the model");

        for (JsonObject element : elements()) {
            if (!element.has("rotation")) {
                continue;
            }
            JsonObject rotation = element.getAsJsonObject("rotation");
            assertEquals("x", rotation.get("axis").getAsString(), "a louvre tilts about the line it runs along");
            JsonArray origin = rotation.getAsJsonArray("origin");
            double tilt = Math.toRadians(rotation.get("angle").getAsDouble());
            assertTrue(tilt != 0.0D, "a flat louvre is a shelf");
            assertTrue(at(element, "from", 0) >= rim && at(element, "to", 0) <= 16.0D - rim,
                    "a louvre runs into the side walls");
            for (String cornerY : List.of("from", "to")) {
                for (String cornerZ : List.of("from", "to")) {
                    double dy = at(element, cornerY, 1) - origin.get(1).getAsDouble();
                    double dz = at(element, cornerZ, 2) - origin.get(2).getAsDouble();
                    double y = origin.get(1).getAsDouble() + dy * Math.cos(tilt) - dz * Math.sin(tilt);
                    double z = origin.get(2).getAsDouble() + dy * Math.sin(tilt) + dz * Math.cos(tilt);
                    assertTrue(y >= rim && y <= 16.0D - rim, "a louvre reaches y=" + y + ", into the rim");
                    assertTrue(z >= 0.0D && z <= throat, "a louvre reaches z=" + z + ", out of the throat");
                }
            }
        }
    }

    @Test
    void everyTextureTheModelNamesIsDrawn() {
        JsonObject textures = read(ASSETS.resolve("models/block/cooling_vent.json")).getAsJsonObject("textures");
        for (Map.Entry<String, JsonElement> texture : textures.entrySet()) {
            String name = texture.getValue().getAsString();
            assertTrue(name.startsWith("aerowarptics:block/"), texture.getKey() + " is " + name);
            Path file = ASSETS.resolve("textures/block").resolve(name.substring(name.lastIndexOf('/') + 1) + ".png");
            assertTrue(Files.exists(file), texture.getKey() + " names " + file + ", which does not exist");
        }
        for (JsonObject element : elements()) {
            for (Map.Entry<String, JsonElement> face : element.getAsJsonObject("faces").entrySet()) {
                String key = face.getValue().getAsJsonObject().get("texture").getAsString();
                assertTrue(key.startsWith("#") && textures.has(key.substring(1)),
                        "a face asks for " + key + ", which the model does not define");
            }
        }
    }

    /**
     * Ice is ice by a tag of this mod's own that holds vanilla's. Read here because a tag file with a typo
     * in it loads as an empty tag, and then ice quietly cools nothing.
     */
    @Test
    void iceOfAnyKindIsADriveCoolant() {
        JsonObject tag = read(DATA.resolve("aerowarptics/tags/block/drive_coolant.json"));
        List<String> values = new ArrayList<>();
        tag.getAsJsonArray("values").forEach(value -> values.add(value.getAsString()));
        assertTrue(values.contains("#minecraft:ice"), "every kind of ice is in vanilla's ice tag: " + values);
        assertFalse(tag.has("replace") && tag.get("replace").getAsBoolean(),
                "replacing would throw away what a data pack added");
        assertTrue(source("cooling/Coolants.java").contains("AeroWarptics.id(\"drive_coolant\")"),
                "the code reads a tag the data does not define");
    }
}
